import { existsSync } from 'node:fs';
import { mkdtemp, rm } from 'node:fs/promises';
import type { AddressInfo } from 'node:net';
import path from 'node:path';
import os from 'node:os';
import express from 'express';
import { chromium } from 'playwright-core';
import { expect, it, vi } from 'vitest';
import { createApp } from '../src/server/app';
import type { Config } from '../src/server/config';
import { Registry } from '../src/server/registry';
import { Store } from '../src/server/store';
import { MockProvider } from '../src/server/providers/mock';
import { QUIET } from './helpers';

const chrome = process.env.CHROME_PATH ?? '/opt/google/chrome/chrome';
it.skipIf(!existsSync(chrome) || !existsSync('dist/client/index.html'))('manages business email, passwords and grants through the real dashboard', async () => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'access-ui-'));
  const store = new Store(dir); await store.init();
  const mail = { check: vi.fn(async () => {}), list: vi.fn(async () => [{ id: '1:2', from: 'supplier@paperclips.example', subject: 'Verify Only Paperclips', date: '' }]), read: vi.fn(async () => ({ id: '1:2', from: 'supplier@paperclips.example', subject: 'Verify Only Paperclips', text: 'Your fixture verification code is 123456.', date: '', truncated: false })), send: vi.fn(async () => {}) };
  const registry = new Registry(store, new MockProvider(QUIET), { access: { mail } });
  const config: Config = { port: 0, host: '127.0.0.1', dataDir: dir, provider: 'mock', providerReason: 'test', production: true, workspace: 'default', anthropicAmbient: false, claudeCode: { command: 'claude', extraUsage: false, blocked: null } };
  const app = createApp(registry, config); app.use(express.static(path.resolve('dist/client')));
  const server = app.listen(0, '127.0.0.1');
  await new Promise<void>(resolve => server.once('listening', resolve));
  const base = 'http://127.0.0.1:' + (server.address() as AddressInfo).port;
  const browser = await chromium.launch({ executablePath: chrome, headless: true, chromiumSandbox: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  page.setDefaultTimeout(10000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const text = () => page.locator('body').innerText();
  try {
    await page.goto(base);
    await page.getByRole('button', { name: 'Try Only Paperclips', exact: true }).click();
    await page.getByRole('tab', { name: 'Email & accounts', exact: true }).click();
    await page.getByLabel('Vault passphrase', { exact: true }).fill('a safe test vault passphrase');
    await page.getByLabel('Repeat vault passphrase', { exact: true }).fill('a safe test vault passphrase');
    await page.getByLabel(/Keep unlocked until/).check();
    await page.getByRole('button', { name: 'Create vault', exact: true }).click();
    await page.getByRole('button', { name: 'Connect Gmail with Google', exact: true }).waitFor();
    expect(await text()).toContain('Google sign-in needs one-time server setup');
    expect(await text()).toContain('stays unlocked');
    await page.getByText('Other providers: IMAP and SMTP', { exact: true }).click();
    await page.getByLabel('Email address', { exact: true }).fill('office@paperclips.example');
    await page.getByLabel('App password', { exact: true }).fill('test-mail-secret');
    await page.getByLabel('IMAP host (TLS, port 993)', { exact: true }).fill('imap.paperclips.example');
    await page.getByLabel('SMTP host', { exact: true }).fill('smtp.paperclips.example');
    await page.getByRole('checkbox', { name: /^COO/ }).check();
    await page.getByRole('button', { name: 'Connect mailbox', exact: true }).click();
    await page.getByRole('button', { name: 'Read inbox', exact: true }).click();
    await page.getByRole('button', { name: /Verify Only Paperclips/ }).click();
    await page.getByText('Your fixture verification code is 123456.', { exact: true }).waitFor();
    expect(mail.check).toHaveBeenCalledTimes(1);
    expect(await page.getByLabel('App password', { exact: true }).inputValue()).toBe('');
    await page.getByRole('button', { name: 'Accounts', exact: true }).click();
    await page.getByLabel('Service name', { exact: true }).fill('Paperclip supplier portal');
    await page.getByLabel('Login URL', { exact: true }).fill('https://supplier.paperclips.example/login');
    await page.getByLabel('Account username or email', { exact: true }).fill('office@paperclips.example');
    await page.getByLabel('Existing account password', { exact: true }).fill('test-supplier-secret');
    await page.getByLabel('Mailbox for verification', { exact: true }).selectOption({ label: 'office@paperclips.example' });
    await page.getByRole('checkbox', { name: /^COO/ }).check();
    await page.getByRole('button', { name: 'Save service account', exact: true }).click();
    await page.getByRole('button', { name: 'Reveal password for 30 seconds', exact: true }).click();
    await page.getByRole('button', { name: 'Hide password', exact: true }).waitFor();
    expect(await text()).toContain('test-supplier-secret');
    await page.getByRole('button', { name: 'Hide password', exact: true }).click();
    expect(await text()).not.toContain('test-supplier-secret');
    await page.getByText('Manage access', { exact: true }).click();
    await page.getByRole('button', { name: 'Disable', exact: true }).click();
    await page.getByRole('button', { name: 'Enable', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Enable', exact: true }).click();
    await page.getByRole('button', { name: 'Disable', exact: true }).waitFor();
    await page.getByText('Manage access', { exact: true }).click();
    await page.evaluate(() => window.scrollTo(0, 0));
    if (process.env.UPDATE_SCREENSHOTS === '1') await page.screenshot({ path: 'docs/only-paperclips-access.png', fullPage: true });
    await page.getByRole('button', { name: 'Email drafts', exact: true }).click();
    await page.getByLabel('To', { exact: true }).fill('supplier@paperclips.example');
    await page.getByLabel('Subject', { exact: true }).fill('Paperclip order enquiry');
    await page.getByLabel('Message', { exact: true }).fill('Please quote for ten boxes of paperclips.');
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    await page.getByRole('button', { name: 'Send this email', exact: true }).waitFor();
    expect(mail.send).not.toHaveBeenCalled();
    await page.getByRole('button', { name: 'Send this email', exact: true }).click();
    await page.locator('.ops-card .tag').filter({ hasText: /^sent$/ }).waitFor();
    expect(mail.send).toHaveBeenCalledTimes(1);
    await page.getByRole('button', { name: 'Lock vault', exact: true }).click();
    await page.getByRole('button', { name: 'Unlock vault', exact: true }).waitFor();
    expect(await text()).not.toContain('Paperclip order enquiry');
    await page.getByLabel('Vault passphrase', { exact: true }).fill('a safe test vault passphrase');
    await page.getByRole('button', { name: 'Unlock vault', exact: true }).click();
    await page.getByRole('button', { name: 'Accounts', exact: true }).click();
    await page.getByRole('heading', { name: 'Paperclip supplier portal', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Mailboxes', exact: true }).click();
    expect(await text()).toContain('COO: reads and drafts');
    await page.getByRole('button', { name: 'Accounts', exact: true }).click();
    expect(await text()).toContain('COO: signs in and reads only');
    // What a role may do is set on a page of its own, and what it holds shows up where the connection is.
    const tick = (label: string) => page.getByRole('checkbox', { name: 'COO: ' + label, exact: true });
    await page.getByRole('tab', { name: 'Privileges', exact: true }).click();
    expect(await tick('Act on accounts').isChecked()).toBe(false);
    expect(await tick('Read assigned mailboxes').isChecked()).toBe(true);
    await tick('Sign in and read').click();
    await page.waitForFunction(() => !document.querySelector<HTMLInputElement>('[aria-label="COO: Sign in and read"]')?.checked);
    await tick('Act on accounts').click();
    await page.getByText('can both read mail and act on accounts').waitFor();
    expect(await tick('Sign in and read').isChecked()).toBe(true);
    await page.evaluate(() => window.scrollTo(0, 0));
    if (process.env.UPDATE_SCREENSHOTS === '1') await page.screenshot({ path: 'docs/only-paperclips-privileges.png', fullPage: true });
    await page.reload();
    await page.getByRole('tab', { name: 'Privileges', exact: true }).click();
    expect(await tick('Act on accounts').isChecked()).toBe(true);
    await page.getByRole('tab', { name: 'Board', exact: true }).click();
    await page.getByText('What the COO may do has changed').first().waitFor();
    await page.getByRole('tab', { name: 'Email & accounts', exact: true }).click();
    await page.getByRole('button', { name: 'Accounts', exact: true }).click();
    await page.getByText('COO: can act').waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await page.getByRole('tab', { name: 'Privileges', exact: true }).click();
    await tick('Act on accounts').waitFor();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    expect(errors).toEqual([]);
  } finally {
    await browser.close();
    await registry.shutdown();
    server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve()));
    await rm(dir, { recursive: true, force: true });
  }
}, 40_000);
